/**
 * Resolve LAN IPv4, write mobile/.env for Expo, print the game URL.
 * `mobile:lan` is meant to configure — it exits after writing (by design).
 */
import { networkInterfaces } from 'node:os';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mobileEnv = join(root, 'mobile', '.env');

function lanIps() {
  const nets = networkInterfaces();
  const ips = [];
  for (const list of Object.values(nets)) {
    if (!list) continue;
    for (const n of list) {
      if (n.family === 'IPv4' && !n.internal) ips.push(n.address);
    }
  }
  return ips;
}

const ips = lanIps();
const ip = ips[0] ?? '127.0.0.1';
const url = `http://${ip}:5173/?touch=1`;

writeFileSync(
  mobileEnv,
  `# Generated by bun run mobile:lan — do not commit\n` +
    `EXPO_PUBLIC_GAME_URL=${url}\n`,
  'utf8',
);

console.log(url);
console.log(`Wrote ${mobileEnv}`);
if (ips.length > 1) {
  console.log(`(other NICs: ${ips.slice(1).join(', ')})`);
}
console.log('');
console.log('Next:');
console.log('  1. bun run dev          # Vite must listen on 0.0.0.0:5173');
console.log('  2. Restart Expo Metro   # so it picks up mobile/.env');
console.log('     cd mobile && bunx expo start -c');
console.log('  3. Reload the app on device (or re-run expo run:android)');
console.log('');
console.log('Do NOT use 10.0.2.2 on a physical phone — that is emulator-only.');
