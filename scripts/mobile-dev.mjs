/**
 * Dev on device: LAN Vite + debug app.
 * Usage: bun run mobile:dev
 *   (starts Vite if needed, writes .env, runs expo run:android)
 */
import { spawn } from 'node:child_process';
import { createConnection } from 'node:net';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeFileSync } from 'node:fs';
import { networkInterfaces } from 'node:os';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mobile = join(root, 'mobile');

function lanIp() {
  const nets = networkInterfaces();
  for (const list of Object.values(nets)) {
    if (!list) continue;
    for (const n of list) {
      if (n.family === 'IPv4' && !n.internal) return n.address;
    }
  }
  return '127.0.0.1';
}

function portOpen(port) {
  return new Promise((resolve) => {
    const s = createConnection({ port, host: '127.0.0.1' }, () => {
      s.end();
      resolve(true);
    });
    s.on('error', () => resolve(false));
  });
}

const ip = lanIp();
const url = `http://${ip}:5173/?touch=1`;
writeFileSync(
  join(mobile, '.env'),
  `# Dev — generated by mobile:dev\n` +
    `EXPO_PUBLIC_GAME_URL=${url}\n` +
    `EXPO_PUBLIC_GAME_BUNDLE=0\n`,
  'utf8',
);
console.log(`Game URL → ${url}`);

let vite = null;
if (!(await portOpen(5173))) {
  console.log('Starting Vite on :5173 …');
  vite = spawn('bun', ['run', 'dev'], {
    cwd: root,
    stdio: 'inherit',
    shell: true,
  });
  for (let i = 0; i < 40; i++) {
    await new Promise((r) => setTimeout(r, 250));
    if (await portOpen(5173)) break;
  }
} else {
  console.log('Vite already on :5173');
}

const expo = spawn('bunx', ['expo', 'run:android'], {
  cwd: mobile,
  stdio: 'inherit',
  shell: true,
  env: {
    ...process.env,
    EXPO_PUBLIC_GAME_URL: url,
    EXPO_PUBLIC_GAME_BUNDLE: '0',
  },
});

function shutdown() {
  expo.kill();
  vite?.kill();
  process.exit(0);
}
process.on('SIGINT', shutdown);
process.on('SIGTERM', shutdown);

expo.on('exit', (code) => {
  vite?.kill();
  process.exit(code ?? 0);
});
